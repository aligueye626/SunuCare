function addDaysToIso(baseIso: string, days: number): string {
  const parts = baseIso.split('-').map(Number);
  const d = new Date(Date.UTC(parts[0], parts[1] - 1, parts[2] + days));
  return d.toISOString().split('T')[0];
}

